"""
Generate revision/RESULTS_TABLES.md: every number of the revision experiments as Markdown
tables, read directly from evaluation/results_v2 and evaluation/analysis_v2 (no hand copying).

Usage:
    python revision/scripts/make_results_tables.py
"""

import csv
import json
from pathlib import Path

RES = Path("evaluation/results_v2")
ANA = Path("evaluation/analysis_v2")
OUT = Path("revision/RESULTS_TABLES.md")
MODELS = ["qwen2.5-coder-0.5b", "qwen2.5-coder-1.5b", "qwen2.5-coder-3b", "qwen2.5-coder-7b"]
MODEL_LABEL = {"qwen2.5-coder-0.5b": "0.5B", "qwen2.5-coder-1.5b": "1.5B", "qwen2.5-coder-3b": "3B",
               "qwen2.5-coder-7b": "7B", "gpt-4.1-mini": "GPT-4.1-mini"}
DATASETS = {"spider_vi": "ViSpider", "bird_vi": "ViBIRD"}


def meta(ds, stem):
    p = RES / ds / f"{stem}.meta.json"
    return json.loads(p.read_text()) if p.exists() else None


def pct(x):
    return "–" if x is None else f"{100 * x:.1f}"


def read_csv(path):
    with open(path, encoding="utf-8") as f:
        return list(csv.DictReader(f))


def table(headers, rows):
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(lines)


def ex_grid(ds, stems, models=MODELS, field="ex"):
    rows = []
    for m in models:
        row = [MODEL_LABEL[m]]
        for s in stems:
            mm = meta(ds, s.format(m=m))
            row.append(pct(mm[field]) if mm else "–")
        rows.append(row)
    return rows


def main():
    md = ["# Revision results — all tables",
          "",
          "Generated by `revision/scripts/make_results_tables.py` from `evaluation/results_v2/` and "
          "`evaluation/analysis_v2/`. Do not edit by hand; re-run the script instead. "
          "EX = execution accuracy (%), set-based comparison of result rows. "
          "Dev sets: ViSpider n = 1,034; ViBIRD n = 1,534. k = number of columns kept by e5 column retrieval "
          "(PK/FK columns of kept tables are added on top).",
          ""]

    # 1. Main ablation
    cfg = [("baseline", "baseline_{m}"), ("+aug", "plusaug_{m}"), ("+link", "pluslink_{m}"),
           ("augret", "augret_{m}"), ("full", "full_{m}"), ("+link (LLM-select)", "pluslink_llm_{m}"),
           ("full (LLM-select) = full_llm", "full_llm_{m}"), ("augret (BM25)", "augret_bm25_{m}")]
    md += ["## 1. Main ablation (Vietnamese questions, k = 10)", ""]
    for ds, name in DATASETS.items():
        for field, label in (("ex", "EX %"), ("invalid_rate", "Invalid SQL %")):
            md += [f"### {name} — {label}", ""]
            rows = ex_grid(ds, [s for _, s in cfg], field=field)
            g = [MODEL_LABEL["gpt-4.1-mini"]] + [pct(meta(ds, s.format(m="gpt-4.1-mini"))[field])
                                                 if meta(ds, s.format(m="gpt-4.1-mini")) else "–" for _, s in cfg]
            md += [table(["Model"] + [c for c, _ in cfg], rows + [g]), ""]

    # 2. Significance
    md += ["## 2. Paired significance tests (McNemar, Holm-adjusted within family; paired bootstrap 95% CI)", "",
           "Δ = EX(a) − EX(b) in points. Full list: `evaluation/analysis_v2/stats/{dataset}_pairs.csv`. "
           "Families: ablation (all pairs of the five configs), language, k, linker, values.", ""]
    key_pairs = [("full_{m}", "baseline_{m}"), ("plusaug_{m}", "baseline_{m}"), ("pluslink_{m}", "baseline_{m}"),
                 ("augret_{m}", "pluslink_{m}"), ("full_{m}", "pluslink_{m}"), ("full_llm_{m}", "baseline_{m}"),
                 ("full_llm_{m}", "full_{m}"), ("full_llm_{m}", "pluslink_llm_{m}"),
                 ("pluslink_llm_{m}", "baseline_{m}")]
    for ds, name in DATASETS.items():
        stats = {(r["a"], r["b"]): r for r in read_csv(ANA / "stats" / f"{ds}_pairs.csv")}
        rows = []
        for m in MODELS + ["gpt-4.1-mini"]:
            for a, b in key_pairs:
                r = stats.get((a.format(m=m), b.format(m=m)))
                if r:
                    rows.append([MODEL_LABEL[m], r["a"].replace("_" + m, ""), r["b"].replace("_" + m, ""),
                                 f"{100 * float(r['delta']):+.1f}",
                                 f"[{100 * float(r['ci_low']):+.1f}, {100 * float(r['ci_high']):+.1f}]",
                                 f"{r['a_only']}/{r['b_only']}", r["p_holm"], "yes" if r["significant"] == "1" else "no"])
        md += [f"### {name}", "", table(["Model", "a", "b", "Δ EX", "95% CI", "a-only / b-only correct",
                                          "p (Holm)", "sig. α=0.05"], rows), ""]

    # 3. Language
    md += ["## 3. English vs Vietnamese questions (E3), EX %", ""]
    for ds, name in DATASETS.items():
        rows = ex_grid(ds, ["baseline_{m}", "full_{m}", "baseline_en_{m}", "full_en_{m}"])
        md += [f"### {name}", "", table(["Model", "baseline (VI)", "full (VI)", "baseline (EN)", "full (EN)"], rows), ""]

    # 4. k sensitivity
    md += ["## 4. Sensitivity to k (E5), EX %", ""]
    ks = {"bird_vi": [10, 20, 30, 50], "spider_vi": [5, 10, 20]}
    for ds, name in DATASETS.items():
        rows = []
        for m in ("qwen2.5-coder-1.5b", "qwen2.5-coder-7b"):
            for c, tag in (("+link", "pluslink"), ("full", "full")):
                row = [MODEL_LABEL[m], c]
                for k in ks[ds]:
                    mm = meta(ds, f"{tag}_{m}" if k == 10 else f"{tag}_k{k}_{m}")
                    row.append(pct(mm["ex"]) if mm else "–")
                row.append(pct(meta(ds, f"baseline_{m}")["ex"]))
                rows.append(row)
        md += [f"### {name}", "", table(["Model", "Config"] + [f"k={k}" for k in ks[ds]] + ["baseline"], rows), ""]

    # 5. Recall
    md += ["## 5. Schema-filtering recall (E4, E7; no SQL generation)", "",
           "all_tables_kept = share of questions whose every gold table survives filtering; col_recall = mean share "
           "of gold columns kept; kept_col_ratio = mean share of the database's columns kept (incl. PK/FK expansion). "
           "Gold tables/columns extracted from the gold SQL with sqlglot.", ""]
    for ds, name in DATASETS.items():
        rows = []
        for path in (ANA / "recall" / f"{ds}_summary.csv", ANA / "recall_baselines" / f"{ds}_summary.csv"):
            for r in read_csv(path):
                if r["setting"] in ("k5", "k10", "k20", "k30", "k50", "r0.25", "llm"):
                    rows.append([r["linker"], r["setting"], pct(float(r["all_tables_kept"])),
                                 pct(float(r["table_recall"])), pct(float(r["col_recall"])),
                                 pct(float(r["all_cols_kept"])), pct(float(r["kept_col_ratio"])), r["n_cols_kept"]])
        md += [f"### {name}", "", table(["Linker", "Setting", "All gold tables kept %", "Table recall %",
                                          "Column recall %", "All gold cols kept %", "Kept col ratio %",
                                          "Cols kept (mean)"], rows), ""]

    # 6. Sample values cap (E9, E10 v50)
    md += ["## 6. Sample values capped at 50 characters (E9; ViBIRD), EX % (questions with truncated schema)", ""]
    rows = []
    for m in MODELS:
        row = [MODEL_LABEL[m]]
        for s in ("plusaug_{m}", "plusaug_{m}_v50", "full_{m}", "full_{m}_v50", "full_llm_{m}", "full_llm_{m}_v50"):
            mm = meta("bird_vi", s.format(m=m))
            row.append(f"{pct(mm['ex'])} ({mm['n_truncated']})" if mm else "–")
        rows.append(row)
    md += [table(["Model", "+aug", "+aug ≤50", "full", "full ≤50", "full_llm", "full_llm ≤50"], rows), ""]

    # 7. Breakdowns
    md += ["## 7. Breakdowns", "", "### 7.1 Invalid SQL by error type (counts; A1)", ""]
    for ds, name in DATASETS.items():
        rows = []
        for r in read_csv(ANA / "breakdown" / f"{ds}_runs.csv"):
            stem = r["run"]
            if any(stem == f"{c}_{m}" for c in ("baseline", "full", "full_llm") for m in MODELS + ["gpt-4.1-mini"]):
                rows.append([stem, r["n"], pct(float(r["invalid_rate"])), r["error_syntax"], r["error_no_table"],
                             r["error_no_column"], r["error_ambiguous_column"], r["error_other"], r["timeout"],
                             r["empty_sql"]])
        md += [f"#### {name}", "", table(["Run", "n", "Invalid %", "syntax", "no such table", "no such column",
                                           "ambiguous column", "other", "timeout", "empty"], rows), ""]
    md += ["### 7.2 EX by difficulty (A2), %", ""]
    for ds, name, grouping in (("spider_vi", "ViSpider (official Spider hardness)", "hardness"),
                               ("bird_vi", "ViBIRD (difficulty)", "difficulty")):
        d = {}
        levels = []
        for r in read_csv(ANA / "breakdown" / f"{ds}_difficulty.csv"):
            if r["grouping"] == grouping:
                d[(r["run"], r["level"])] = (r["ex"], r["n"])
                if r["level"] not in levels:
                    levels.append(r["level"])
        order = [l for l in ("easy", "medium", "hard", "extra", "simple", "moderate", "challenging") if l in levels]
        rows = []
        for c in ("baseline", "full", "full_llm"):
            for m in MODELS + ["gpt-4.1-mini"]:
                stem = f"{c}_{m}"
                if (stem, order[0]) in d:
                    rows.append([stem] + [pct(float(d[(stem, l)][0])) for l in order])
        ns = [d[(next(iter(d))[0], l)][1] for l in order]
        md += [f"#### {name}", "", table(["Run"] + [f"{l} (n={n})" for l, n in zip(order, ns)], rows), ""]
    md += ["### 7.3 EX when every gold table survives filtering vs when one is dropped (A5), %", ""]
    for ds, name in DATASETS.items():
        rows = [[r["run"], r["n_all_gold_kept"], pct(float(r["ex_all_gold_kept"])) if r["ex_all_gold_kept"] else "–",
                 r["n_gold_missing"], pct(float(r["ex_gold_missing"])) if r["ex_gold_missing"] else "–"]
                for r in read_csv(ANA / "breakdown" / f"{ds}_gold_tables.csv")
                if not any(t in r["run"] for t in ("_en_", "_v50"))]
        md += [f"#### {name}", "", table(["Run", "n all kept", "EX all kept", "n missing", "EX missing"], rows), ""]
    md += ["### 7.4 Prompt length (A6)", "",
           "n_over_4096 = prompts longer than the v1 input limit of 4,096 tokens (v1 truncated these on the right, "
           "cutting the question).", ""]
    for ds, name in DATASETS.items():
        rows = []
        for r in read_csv(ANA / "breakdown" / f"{ds}_runs.csv"):
            if r["run"] in [f"{c}_qwen2.5-coder-7b" for c in ("baseline", "plusaug", "pluslink", "augret", "full", "full_llm")]:
                rows.append([r["run"].replace("_qwen2.5-coder-7b", ""), r["prompt_tokens_median"], r["prompt_tokens_p95"],
                             r["prompt_tokens_max"], r["n_over_4096"], r["n_truncated"]])
        md += [f"#### {name} (Qwen2.5-Coder tokenizer)", "",
               table(["Config", "median", "p95", "max", "n > 4096", "n truncated at 32k"], rows), ""]
    md += ["### 7.5 Automatic error categories of wrong predictions (A3), counts", ""]
    for ds, name in DATASETS.items():
        rows = []
        for r in read_csv(ANA / "errors" / f"{ds}_categories.csv"):
            if r["run"] in [f"{c}_{m}" for c in ("baseline", "full", "full_llm") for m in ("qwen2.5-coder-1.5b", "qwen2.5-coder-7b")]:
                rows.append([r["run"], r["n_errors"], r["invalid_sql"], r["gold_missing"], r["wrong_tables"],
                             r["wrong_columns"], r["wrong_agg_group"], r["wrong_condition"], r["wrong_order"], r["other"]])
        md += [f"#### {name}", "", table(["Run", "errors", "invalid SQL", "gold table missing", "wrong tables",
                                           "wrong columns", "agg/GROUP BY", "condition/value", "ORDER/LIMIT", "other"], rows), ""]

    # 8. Official EM
    md += ["## 8. Official Spider exact-set-match (EM), ViSpider, %", "",
           "The Spider parser cannot parse many LLM outputs (table aliases without AS, column aliases in SELECT); "
           "those count as wrong, so EM is far below EX. n_pred_unparsed = predictions the parser rejected.", ""]
    rows = [[r["run"], pct(float(r["official_em"])), r["n_pred_unparsed"]] + [pct(float(r[f"em_{l}"])) for l in ("easy", "medium", "hard", "extra")]
            for r in read_csv(ANA / "official_em" / "spider_vi_runs.csv")
            if any(r["run"] == f"{c}_{m}" for c in ("baseline", "full", "full_llm") for m in MODELS + ["gpt-4.1-mini"])]
    md += [table(["Run", "EM", "unparsed", "easy", "medium", "hard", "extra"], rows), ""]

    # 9. Cost
    md += ["## 9. Cost (E8)", "", "### 9.1 Online, batch size 1, 200 sampled questions, RTX 4090, HF transformers", ""]
    rows = [[DATASETS[r["dataset"]], r["config"], r["model"].replace("-Instruct", ""), r["link_ms_p50"], r["gen_ms_p50"],
             r["total_ms_p50"], r["total_ms_p95"], r["prompt_tokens_mean"], r["peak_vram_gb"]]
            for r in read_csv(ANA / "latency" / "summary.csv")]
    md += [table(["Dataset", "Config", "Model", "link ms p50", "gen ms p50", "total ms p50", "total ms p95",
                  "prompt tokens", "peak VRAM GB"], rows), "", "### 9.2 Offline / auxiliary stages", ""]
    rows = [[r["stage"], r["dataset"], r["n_db"], r["seconds"], r["peak_vram_gb"], r["seconds_per_db_max"],
             r.get("ms_per_question", "")] for r in read_csv(ANA / "latency" / "offline.csv")]
    md += [table(["Stage", "Dataset", "#DB", "seconds", "peak VRAM GB", "max s per DB", "ms per question (batch 8)"], rows), ""]

    # 10. Human evaluation
    md += ["## 10. Human evaluation (T1–T3)", "",
           "Two annotators, independent; disagreements adjudicated by the first author. Agreement statistics on the two "
           "independent annotations (before adjudication).", "", "### 10.1 Agreement", ""]
    rows = [[r["task"], r["sheet"], r["criterion"], r["n_pairs"], pct(float(r["raw_agreement"])), r["kappa"],
             r["kappa_linear_weighted"] or "–", r["gwet_ac1"], r["n_adjudicated"], r["n_unresolved"]]
            for r in read_csv(ANA / "human" / "agreement.csv")]
    md += [table(["Task", "Part", "Criterion", "n", "Raw agreement %", "Cohen κ", "Linear weighted κ", "Gwet AC1",
                  "Adjudicated", "Unresolved"], rows), "", "### 10.2 Final (adjudicated) values", ""]
    rows = [[r["task"], r["sheet"], r["criterion"], r["value"], r["count"], pct(float(r["share"])), r["n"], r["mean"] or ""]
            for r in read_csv(ANA / "human" / "distribution.csv")]
    md += [table(["Task", "Part", "Criterion", "Value", "Count", "Share %", "n", "Mean (1–3)"], rows), "",
           "### 10.3 T3: automatic error category confirmed by humans", ""]
    rows = [[r["group"], r["n"], r["auto_label_confirmed"], pct(float(r["share"]))] for r in read_csv(ANA / "human" / "t3_by_group.csv")]
    md += [table(["Group", "n", "confirmed", "%"], rows), "",
           "Groups: A = ViBIRD 7B, baseline correct / full wrong; B = ViSpider 0.5B, full correct / baseline wrong "
           "(baseline output reviewed); C = wrong under all five configs, 7B. Confusion matrix: "
           "`evaluation/analysis_v2/human/t3_confusion.csv`.", ""]

    OUT.write_text("\n".join(md), encoding="utf-8")
    print(f"Saved {OUT}")


if __name__ == "__main__":
    main()
